catalog = json.loads(CATALOG.read_text())
# Keys the last build no longer found (their code was removed or reworded) are marked stale by xcstringstool.
stale = [k for k, v in catalog["strings"].items() if v.get("extractionState") == "stale"]
for key in stale:
    del catalog["strings"][key]
if stale: print("removed stale keys:", *stale, sep="\n  ")
missing = []
for key, entry in catalog["strings"].items():
    if key in NO_TRANSLATE:
        entry["shouldTranslate"] = False
        continue
    entry.pop("shouldTranslate", None)
    if key in DE:
        entry.setdefault("localizations", {})["de"] = {"stringUnit": {"state": "translated", "value": DE[key]}}
    else:
        missing.append(key)
unused = sorted(set(DE) - set(catalog["strings"]))
CATALOG.write_text(json.dumps(catalog, indent=2, ensure_ascii=False, sort_keys=True) + "\n")
print(f"{len(catalog['strings'])} keys, {len(DE)} German translations")
if missing: print("UNTRANSLATED:", *missing, sep="\n  ")
if unused: print("UNUSED translations (key no longer in code):", *unused, sep="\n  ")
sys.exit(1 if missing else 0)
